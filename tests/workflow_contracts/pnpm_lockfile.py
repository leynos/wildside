"""Read the package names a pnpm lockfile resolves.

A repository-wide absence contract has to ask both lockfiles whether a package
is present, because the two are generated by different package managers and
can disagree. The Bun side is answered by `bun_lockfile.py`; this module
answers the pnpm side from the `packages` and `snapshots` tables.

The lockfile is read through `strict_yaml`, so a document that repeats a key
is refused rather than silently collapsed to its last value. That matters
here: a duplicate `extract-zip` key could hide the entry a text match would
otherwise find.
"""

from __future__ import annotations

import collections.abc as cabc

import strict_yaml

#: The lockfile tables that list resolved packages. `packages` holds each
#: package's metadata and `snapshots` holds each resolved dependency graph;
#: both are keyed by `name@version`, with peer suffixes in the snapshots.
PACKAGE_TABLES = ("packages", "snapshots")


def base_name(key: str) -> str:
    """Return the package name in a pnpm package key.

    pnpm qualifies a key with its version and, in `snapshots`, with the peer
    releases it resolved against. A scoped name begins with `@`, which is not
    the version separator.

    Parameters
    ----------
    key : str
        A `packages` or `snapshots` key.

    Returns
    -------
    str
        The package name without its version or peer suffix.

    Raises
    ------
    ValueError
        If the key names no package.

    Examples
    --------
    >>> base_name("extract-zip@2.0.1")
    'extract-zip'
    >>> base_name("@puppeteer/browsers@3.2.6(proxy-agent@8.0.1)")
    '@puppeteer/browsers'
    >>> base_name("@scope/pkg@1.0.0-beta.1")
    '@scope/pkg'
    """
    if not isinstance(key, str) or not key:
        message = "a pnpm package key must name a package"
        raise ValueError(message)
    specifier = key.split("(", 1)[0]
    search_from = 1 if specifier.startswith("@") else 0
    separator = specifier.find("@", search_from)
    name = specifier if separator == -1 else specifier[:separator]
    if not name:
        message = f"a pnpm package key names no package: {key!r}"
        raise ValueError(message)
    return name


def package_names(tables: cabc.Mapping[str, cabc.Mapping[str, object]]) -> set[str]:
    """Return the package names both tables resolve.

    Parameters
    ----------
    tables : collections.abc.Mapping[str, collections.abc.Mapping[str, object]]
        The parsed `packages` and `snapshots` tables.

    Returns
    -------
    set[str]
        The base name of every key in either table.

    Examples
    --------
    >>> package_names({"packages": {"a@1.0.0": {}}, "snapshots": {}})
    {'a'}
    >>> package_names({"packages": {}, "snapshots": {"b@2.0.0(c@1.0.0)": {}}})
    {'b'}
    """
    names: set[str] = set()
    for table in tables.values():
        names.update(base_name(key) for key in table)
    return names


def parse_tables(text: str) -> dict[str, cabc.Mapping[str, object]]:
    r"""Parse a pnpm lockfile's package tables, refusing a repeated key.

    Parameters
    ----------
    text : str
        The lockfile's text.

    Returns
    -------
    dict[str, collections.abc.Mapping[str, object]]
        The `packages` and `snapshots` tables.

    Raises
    ------
    yaml.YAMLError
        If the text is not YAML, or a mapping in it repeats a key.
    TypeError
        If the document is not a mapping, or either table is missing or is
        not a mapping.

    Examples
    --------
    >>> sorted(parse_tables("packages: {a@1.0.0: {}}\nsnapshots: {}\n"))
    ['packages', 'snapshots']
    """
    document = strict_yaml.load(text)
    if not isinstance(document, cabc.Mapping):
        message = "a pnpm lockfile must hold a mapping"
        raise TypeError(message)
    tables: dict[str, cabc.Mapping[str, object]] = {}
    for field in PACKAGE_TABLES:
        table = document.get(field)
        if not isinstance(table, cabc.Mapping):
            message = f"the pnpm lockfile's {field} table must be a mapping"
            raise TypeError(message)
        tables[field] = table
    return tables


def resolved_names(text: str) -> set[str]:
    r"""Return every package name a pnpm lockfile resolves.

    Parameters
    ----------
    text : str
        The lockfile's text.

    Returns
    -------
    set[str]
        The base name of every `packages` and `snapshots` key.

    Raises
    ------
    yaml.YAMLError
        If the text is not YAML, or a mapping in it repeats a key.
    TypeError
        If the document or either package table is malformed.

    Examples
    --------
    >>> sorted(resolved_names("packages: {a@1.0.0: {}}\nsnapshots: {}\n"))
    ['a']
    """
    return package_names(parse_tables(text))
