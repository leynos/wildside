//! Decoding tests for the retry wrapper's service boundary.
//!
//! A delivery is decoded into the queue's concrete job type before the handler
//! is invoked. A body that does not match that type, or an envelope version
//! this build does not understand, must fail the delivery as fatal rather than
//! reaching handler code that expects the decoded value.

use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};

use apalis_core::error::BoxDynError;
use apalis_core::layers::Service;
use serde_json::{Value, json};

use super::doubles::{
    PersistenceCall, RecordingMetrics, RecordingPersistence, TestJob, WORKER, WriteOutcome,
    service, task,
};
use crate::domain::ports::RouteDeadLetterOutcome;
use crate::outbound::queue::TerminalRetryReason;

/// One delivery through the wrapper, with every effect recorded.
struct Harness {
    persistence: Arc<RecordingPersistence>,
    metrics: Arc<RecordingMetrics>,
    runs: Arc<AtomicUsize>,
}

impl Harness {
    fn new() -> Self {
        Self {
            persistence: Arc::new(RecordingPersistence::new(
                WriteOutcome::Updated,
                WriteOutcome::Updated,
            )),
            metrics: Arc::new(RecordingMetrics::default()),
            runs: Arc::new(AtomicUsize::new(0)),
        }
    }

    /// Deliver `payload` once and count every handler invocation.
    async fn deliver(&self, payload: Value) -> Result<(), BoxDynError> {
        let runs = Arc::clone(&self.runs);
        let handler = move |_job: TestJob, _attempt| {
            runs.fetch_add(1, Ordering::SeqCst);
            async { Ok(()) }
        };
        let mut service = service(
            Arc::clone(&self.persistence),
            Arc::clone(&self.metrics),
            handler,
        );
        service.call(task(payload, 1)).await
    }
}

/// Assert the wrapper performed exactly one fatal terminal write.
///
/// The task id is generated by the harness, so only the classification fields
/// are asserted.
fn assert_single_terminal_write(persistence: &RecordingPersistence) {
    match persistence.calls().as_slice() {
        [
            PersistenceCall::Terminal {
                worker_id,
                attempt,
                reason,
                shrink_limit,
                ..
            },
        ] => {
            assert_eq!(worker_id, WORKER);
            assert_eq!(*attempt, 1);
            assert_eq!(*reason, TerminalRetryReason::Fatal);
            assert!(*shrink_limit);
        }
        other => panic!("expected exactly one terminal write, got {other:?}"),
    }
}

#[tokio::test]
async fn successful_handler_performs_no_persistence_write() {
    let harness = Harness::new();

    let result = harness
        .deliver(json!({"v": "v1", "probeId": "probe"}))
        .await;

    assert!(result.is_ok());
    assert_eq!(harness.runs.load(Ordering::SeqCst), 1);
    assert!(
        harness.persistence.calls().is_empty(),
        "success must not write"
    );
    assert!(harness.metrics.retries().is_empty());
    assert!(harness.metrics.dead_letters().is_empty());
}

#[tokio::test]
async fn malformed_v1_body_never_reaches_the_handler() {
    let harness = Harness::new();

    let result = harness.deliver(json!({"v": "v1"})).await;

    assert!(result.is_err(), "a malformed body is a failed delivery");
    assert_eq!(harness.runs.load(Ordering::SeqCst), 0);
    assert_single_terminal_write(&harness.persistence);
    assert_eq!(
        harness.metrics.dead_letters(),
        vec![RouteDeadLetterOutcome::Fatal]
    );
}

#[tokio::test]
async fn unsupported_version_never_reaches_the_handler() {
    let harness = Harness::new();

    let result = harness
        .deliver(json!({"v": "v2", "probeId": "probe"}))
        .await;

    assert!(
        result.is_err(),
        "an unsupported version is a failed delivery"
    );
    assert_eq!(harness.runs.load(Ordering::SeqCst), 0);
    assert_single_terminal_write(&harness.persistence);
    assert_eq!(
        harness.metrics.dead_letters(),
        vec![RouteDeadLetterOutcome::Fatal]
    );
}
